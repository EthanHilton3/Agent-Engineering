"""Run the same questions through both RAG modes of gc_chatbot.py and save the results side by side.

Written by Claude at Ethan's request.

Usage:
  python compare_modes.py                    # the 7 standard questions -> test_runs.md (overwrites it)
  python compare_modes.py --out other.md --questions "First question?" "Second question?"
"""
import argparse
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

QUESTIONS = [
	"How can I strengthen my faith in Jesus Christ?",
	"What is the church's standpoint on betting?",
	"What is the church's standpoint on personal finances?",
	"How can i be saved?",
	"Why is the world so bad?",
	"What were the main themes of this conference?",  # no single chunk has this answer (GraphRAG territory)
	"What's a good lasagna recipe?",  # off-topic: should be refused
]
MODES = ('preprocess', 'tool')


def run_chatbot(mode: str, question: str) -> str:
	"""One question through gc_chatbot.py, returning everything it prints (searches, answer, cost)."""
	result = subprocess.run(
		[sys.executable, str(HERE / 'gc_chatbot.py'), '--mode', mode, '--question', question],
		stdout=subprocess.PIPE,
		stderr=subprocess.STDOUT,  # SEARCH lines and the cost table go to stderr; keep them in order with the answer
		encoding='utf-8',
	)
	return result.stdout.strip()


def main(out: Path, questions: list[str]):
	lines = [
		'# Test runs: preprocess vs. tool mode',
		'',
		'Generated by compare_modes.py, which runs gc_chatbot.py (gpt-6-luna, reasoning none, 4 talks per search) '
		'once per mode for each question. Search lines show (distance) speaker: title.',
	]
	for question in questions:
		lines += ['', f'## {question}']
		for mode in MODES:
			print(f'{mode}: {question}', file=sys.stderr)
			lines += ['', f'### {mode}', '', '```', run_chatbot(mode, question), '```']

	out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
	print(f'Wrote {out}', file=sys.stderr)


if __name__ == '__main__':
	parser = argparse.ArgumentParser('Compare preprocess and tool modes')
	parser.add_argument('--out', type=Path, default=HERE / 'test_runs.md')
	parser.add_argument('--questions', nargs='+', default=QUESTIONS, help='Questions to run instead of the standard 7.')
	args = parser.parse_args()

	main(out=args.out, questions=args.questions)
